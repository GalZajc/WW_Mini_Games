import { writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import path from 'node:path';

const MAX_ORDER = 10;
const EXPECTED_ONE_SIDED_COUNTS = [0, 1, 1, 2, 7, 18, 60, 196, 704, 2500, 9189];
const DIRECTIONS = [[1, 0], [-1, 0], [0, 1], [0, -1]];

function normalize(cells) {
    let minRow = Infinity;
    let minColumn = Infinity;
    for (const [row, column] of cells) {
        minRow = Math.min(minRow, row);
        minColumn = Math.min(minColumn, column);
    }
    return cells
        .map(([row, column]) => [row - minRow, column - minColumn])
        .sort((a, b) => a[0] - b[0] || a[1] - b[1]);
}

function rotateClockwise(cells) {
    return cells.map(([row, column]) => [column, -row]);
}

function keyOf(cells) {
    return normalize(cells).map(([row, column]) => `${row},${column}`).join(';');
}

// Rotations are equivalent; reflections remain distinct. This is the convention
// that produces the seven familiar tetrominoes (I, O, T, S, Z, J and L).
function canonicalizeOneSided(cells) {
    let rotated = cells;
    let bestKey = null;
    let bestCells = null;
    for (let turn = 0; turn < 4; turn++) {
        const normalized = normalize(rotated);
        const key = normalized.map(([row, column]) => `${row},${column}`).join(';');
        if (bestKey === null || key < bestKey) {
            bestKey = key;
            bestCells = normalized;
        }
        rotated = rotateClockwise(rotated);
    }
    return { key: bestKey, cells: bestCells };
}

function encode(cells) {
    return cells.map(([row, column]) => `${row.toString(36)}${column.toString(36)}`).join('');
}

function generate() {
    const levels = new Map([[1, [{ key: '0,0', cells: [[0, 0]] }]]]);

    for (let order = 2; order <= MAX_ORDER; order++) {
        const unique = new Map();
        for (const shape of levels.get(order - 1)) {
            const occupied = new Set(shape.cells.map(([row, column]) => `${row},${column}`));
            for (const [row, column] of shape.cells) {
                for (const [dr, dc] of DIRECTIONS) {
                    const nextRow = row + dr;
                    const nextColumn = column + dc;
                    if (occupied.has(`${nextRow},${nextColumn}`)) continue;
                    const canonical = canonicalizeOneSided([...shape.cells, [nextRow, nextColumn]]);
                    if (!unique.has(canonical.key)) unique.set(canonical.key, canonical);
                }
            }
        }
        levels.set(order, [...unique.values()].sort((a, b) => a.key.localeCompare(b.key)));
    }

    for (let order = 1; order <= MAX_ORDER; order++) {
        const actual = levels.get(order).length;
        const expected = EXPECTED_ONE_SIDED_COUNTS[order];
        if (actual !== expected) {
            throw new Error(`Order ${order}: generated ${actual}, expected ${expected}.`);
        }
        for (const shape of levels.get(order)) {
            if (keyOf(shape.cells) !== shape.key) throw new Error(`Non-normalized order-${order} shape.`);
        }
    }

    return levels;
}

function renderModule(levels) {
    const rows = [];
    rows.push('// Generated by tools/generate-polyomino-data.mjs. Do not edit by hand.');
    rows.push('// One-sided polyominoes: rotations are equivalent, reflections are distinct.');
    rows.push(`export const MAX_POLYOMINO_ORDER = ${MAX_ORDER};`);
    rows.push(`export const POLYOMINO_COUNTS = Object.freeze(${JSON.stringify(EXPECTED_ONE_SIDED_COUNTS)});`);
    rows.push('export const ENCODED_POLYOMINOES = Object.freeze([');
    rows.push('    null,');
    for (let order = 1; order <= MAX_ORDER; order++) {
        const encoded = levels.get(order).map(shape => encode(shape.cells));
        rows.push(`    Object.freeze(${JSON.stringify(encoded)}),`);
    }
    rows.push(']);');
    rows.push('');
    return rows.join('\n');
}

const levels = generate();
const scriptPath = fileURLToPath(import.meta.url);
const outputPath = path.resolve(path.dirname(scriptPath), '..', 'polyomino-data.js');
await writeFile(outputPath, renderModule(levels), 'utf8');

const total = [...levels.values()].reduce((sum, shapes) => sum + shapes.length, 0);
console.log(`Generated ${total} one-sided polyominoes in ${outputPath}`);
