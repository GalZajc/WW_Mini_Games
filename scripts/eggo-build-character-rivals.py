"""Complete rival descriptor tables with each character's native second palette."""
from pathlib import Path
from datetime import datetime
import json,struct,hashlib
import numpy as np
from PIL import Image
ROOT=Path(__file__).resolve().parents[1];ASSETS=ROOT/'renderer/games/eggo-mania/assets'
PARAMETERS={'resources':'scripts/OUTPUT/eggo-characters_2026-10-04_22-34-09_814879',
 'rom':'C:/Users/galza/Igre/nintendo/gba/Eggo Mania (E) (M6).gba','rival_palette_offset':32,'random_seed':None}
resources=ROOT/PARAMETERS['resources'];rom=Path(PARAMETERS['rom']).read_bytes()
chars=json.loads((resources/'measurement.json').read_text())['characters'];result={}
rgb=lambda p:np.stack([(p>>s&31)*255//31 for s in (0,5,10)],axis=-1).astype('uint8')
for name,resource in chars.items():
 offset=resource['palette']-0x08000000
 original=rgb(np.frombuffer(rom[offset:offset+32],dtype='<u2'))
 target=rgb(np.frombuffer(rom[offset+32:offset+64],dtype='<u2'))
 image=np.array(Image.open(resources/(name+'.png')).convert('RGBA'));colors=image[...,:3].copy()
 Image.fromarray(image).save(ASSETS/(name+'-player-native.png'))
 for i in range(1,16):image[np.all(colors==original[i],axis=-1)&(image[...,3]>0),:3]=target[i]
 asset=ASSETS/(name+'-rival-native.png');Image.fromarray(image).save(asset)
 groups={}
 for group,entries in resource['groups'].items():
  pointer=struct.unpack_from('<I',rom,resource['root']-0x08000000+int(group)*4)[0]
  period,table=struct.unpack_from('<II',rom,pointer-0x08000000)
  groups[group]={'row':int(group)-1,'period':period,'table':hex(table),'descriptors':[hex(e['descriptor']) for e in entries]}
 result[name]={'root':resource['root'],'sheet':name+'-rival-native','playerSheet':name+'-player-native','groups':groups}
(ROOT/'renderer/games/eggo-mania/native-character-resources.js').write_text(
 '// Original ROM descriptor tables; generated by scripts/eggo-build-character-rivals.py.\nexport const NATIVE_CHARACTER_RESOURCES='+json.dumps(result,separators=(',',':'))+';\n',encoding='utf-8')
output=ROOT/'scripts/OUTPUT'/('eggo-character-rivals_'+datetime.now().strftime('%Y-%m-%d_%H-%M-%S'));output.mkdir(parents=True)
(output/'parameters.json').write_text(json.dumps({**PARAMETERS,'rom_sha256':hashlib.sha256(rom).hexdigest()},indent=2),encoding='utf-8')
(output/'results.json').write_text(json.dumps(result,indent=2),encoding='utf-8');print(output)
