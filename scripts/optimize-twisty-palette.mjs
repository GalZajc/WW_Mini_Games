import fs from 'node:fs';
// Deterministic maximin search on the sRGB cube's HSV V=1 surface.
const config = { count: 20, channelStep: 8, restarts: 24, exchanges: 100, seed: 73129 };
const linear = x => x <= 0.04045 ? x / 12.92 : ((x + 0.055) / 1.055) ** 2.4;
function lab(rgb) {
    const [r,g,b] = rgb.map(x => linear(x / 255));
    const l = Math.cbrt(.4122214708*r+.5363325363*g+.0514459929*b);
    const m = Math.cbrt(.2119034982*r+.6806995451*g+.1073969566*b);
    const s = Math.cbrt(.0883024619*r+.2817188376*g+.6299787005*b);
    return [.2104542553*l+.793617785*m-.0040720468*s,1.9779984951*l-2.428592205*m+.4505937099*s,.0259040371*l+.7827717662*m-.808675766*s];
}
const candidates=[], seen=new Set();
const values=Array.from({length:Math.ceil(255/config.channelStep)},(_,i)=>i*config.channelStep).concat(255);
for(let axis=0;axis<3;axis++)for(const a of values)for(const b of values){
    const rgb=[a,b];rgb.splice(axis,0,255);const hex=rgb.map(x=>x.toString(16).padStart(2,'0')).join('');
    if(!seen.has(hex)){seen.add(hex);candidates.push({hex,lab:lab(rgb)});}
}
const distance=(a,b)=>a.reduce((sum,x,i)=>sum+(x-b[i])**2,0);
const nearest=(index,selected,skip=-1)=>Math.min(...selected.filter((_,j)=>j!==skip).map(i=>distance(candidates[index].lab,candidates[i].lab)));
let seed=config.seed; const random=()=>{seed=(Math.imul(seed,1664525)+1013904223)>>>0;return seed/2**32;};
let best=[],bestDistance=-1;
for(let run=0;run<config.restarts;run++){
    const selected=[Math.floor(random()*candidates.length)];
    while(selected.length<config.count){let winner=-1,score=-1;for(let i=0;i<candidates.length;i++){const d=nearest(i,selected);if(d>score){score=d;winner=i;}}selected.push(winner);}
    for(let pass=0;pass<config.exchanges;pass++){
        let changed=false;
        for(let j=0;j<selected.length;j++){
            let winner=selected[j],score=nearest(winner,selected,j);
            for(let i=0;i<candidates.length;i++){const d=nearest(i,selected,j);if(d>score+1e-12){score=d;winner=i;}}
            if(winner!==selected[j]){selected[j]=winner;changed=true;}
        }
        if(!changed)break;
    }
    const minimum=Math.min(...selected.map((i,j)=>nearest(i,selected,j)));
    if(minimum>bestDistance){best=selected;bestDistance=minimum;}
}
const colours=best.map(i=>'#'+candidates[i].hex);
const result={config,space:'OKLab Euclidean',constraint:'HSV value = 100%',minimumDistance:Math.sqrt(bestDistance),colours};
fs.writeFileSync('renderer/games/rubiks-cuboid/bright-palette.js', '// Generated by scripts/optimize-twisty-palette.mjs; no runtime optimization.\nexport const BRIGHT_PALETTE = '+JSON.stringify(result,null,2)+';\n');
console.log(JSON.stringify(result));
