"""Install the complete ROM-decoded Factory rival, with its native palette."""
from pathlib import Path
from datetime import datetime
import json, struct, hashlib
import numpy as np
from PIL import Image

ROOT=Path(__file__).resolve().parents[1]
RESOURCES=ROOT/'scripts/OUTPUT/eggo-characters_2026-10-04_22-34-09_814879'
ROM=Path('C:/Users/galza/Igre/nintendo/gba/Eggo Mania (E) (M6).gba')
CAPTURE=ROOT/'scripts/OUTPUT/eggo-reference_2026-10-07_13-02-24_227876/eggo-replay-full-graphics.frame00001.0x5000000'
manifest=json.loads((RESOURCES/'measurement.json').read_text(encoding='utf-8'))
resource=manifest['characters']['bebub'];rom=ROM.read_bytes()
original=np.frombuffer(rom[resource['palette']-0x08000000:resource['palette']-0x08000000+32],dtype='<u2')
palette=np.frombuffer(CAPTURE.read_bytes(),dtype='<u2')[272:288]
rgb=lambda p:np.stack([(p>>s&31)*255//31 for s in (0,5,10)],axis=-1).astype('uint8')
original_rgb=rgb(original);native_rgb=rgb(palette)
image=np.asarray(Image.open(RESOURCES/'bebub.png').convert('RGBA')).copy()
source=image[...,:3].copy()
for i in range(1,16):
    mask=np.all(source==original_rgb[i],axis=-1)&(image[...,3]>0)
    image[mask,:3]=native_rgb[i]
asset=ROOT/'renderer/games/eggo-mania/assets/factory-rival-native.png'
Image.fromarray(image).save(asset)
groups={}
for group,entries in resource['groups'].items():
    pointer=struct.unpack_from('<I',rom,resource['root']-0x08000000+int(group)*4)[0]
    period,table=struct.unpack_from('<II',rom,pointer-0x08000000)
    groups[group]={'row':int(group)-1,'period':period,'table':hex(table),
        'descriptors':[hex(e['descriptor']) for e in entries]}
data={'factory':{'sheet':'factory-rival-native','groups':groups}}
module=ROOT/'renderer/games/eggo-mania/native-rival-resource.js'
module.write_text('// Complete native descriptor tables; generated by scripts/eggo-build-rival-native-resource.py.\nexport const NATIVE_RIVAL_RESOURCES = '+json.dumps(data,separators=(',',':'))+';\n',encoding='utf-8')
out=ROOT/'scripts/OUTPUT'/('eggo-rival-native-resource_'+datetime.now().strftime('%Y-%m-%d_%H-%M-%S_%f'));out.mkdir(parents=True)
params={'experiment':'Install native rival descriptors','source':str(RESOURCES),'palette':str(CAPTURE),
        'rom_sha256':hashlib.sha256(rom).hexdigest(),'asset_sha256':hashlib.sha256(asset.read_bytes()).hexdigest(),
        'root':hex(resource['root']),'random_seed':None,'groups':groups}
(out/'parameters.json').write_text(json.dumps(params,indent=2)+'\n',encoding='utf-8')
print(out)
