"""Decode the palette retained by the first outline after a native throw."""
from pathlib import Path
from datetime import datetime
import hashlib, json, struct

ROOT = Path(__file__).resolve().parents[1]
source = ROOT/'renderer/games/eggo-mania/assets/placed-pieces.json'
manifest = json.loads(source.read_text(encoding='utf-8'))
parameters = {'source':str(source.relative_to(ROOT)),
    'source_sha256':hashlib.sha256(source.read_bytes()).hexdigest(),
    'palette_entry':15, 'encoding':'GBA RGB555',
    'method':'placement descriptor palette bank, retained in OBJ bank 13/14 after throw',
    'source_hashes':{}}
colors = {}
materials = {}
for stage, prefix in manifest['parameters']['sources'].items():
    path = ROOT/(prefix+'.0x5000000')
    palette = path.read_bytes()
    parameters['source_hashes'][str(path.relative_to(ROOT))] = hashlib.sha256(palette).hexdigest()
    colors[stage] = []
    materials[stage] = []
    for kind in range(8):
        descriptors = next(e['descriptors'] for e in manifest['entries']
            if e['stage']==stage and e['kind']==kind and e['rotation']==0)
        banks = {d>>12 for d in descriptors if d}
        assert len(banks)==1, (stage, kind, banks)
        bank=banks.pop()
        material=list(struct.unpack_from('<16H',palette,bank*32))
        colors[stage].append(material[15])
        materials[stage].append(material)
rom_path=Path(manifest['parameters']['rom'])
rom=rom_path.read_bytes()
parameters['initial_obj_palette']={'rom_offset':0xdce90,'bytes':32,
    'rom_sha256':hashlib.sha256(rom).hexdigest()}
initial=list(struct.unpack_from('<16H',rom,parameters['initial_obj_palette']['rom_offset']))
# F3B0..F3D8 uses a separate sprite-material table, not the BG tile bank.
# In Space, kind3 has purple OBJ material despite its bank0 board template.
parameters['throw_palette_table']=0x216924
parameters['throw_palette_bases']={'beanstalk':0x1f6798,'factory':0x1fa300,
 'dragon':0x1fdfa8,'castle':0x2011b0,'pirate':0x205718,'space':0x20911c,
 'jungle':0x20bbbc,'park':0x20fe24}
throw_materials={}
for stage_index,stage in enumerate(parameters['throw_palette_bases']):
    indices=struct.unpack_from('<8I',rom,parameters['throw_palette_table']+stage_index*32)
    base=parameters['throw_palette_bases'][stage]
    throw_materials[stage]=[list(struct.unpack_from('<16H',rom,base+index*32)) for index in indices]
    colors[stage]=[palette[15] for palette in throw_materials[stage]]
out = ROOT/'scripts/OUTPUT'/('eggo-preview-palette_'+datetime.now().strftime('%Y-%m-%d_%H-%M-%S_%f'))
out.mkdir(parents=True)
(out/'parameters.json').write_text(json.dumps(parameters,indent=2)+'\n',encoding='utf-8')
text = '// Native retained outline palette by arena and piece kind; generated by eggo-build-preview-palette.py.\n'
text += 'export const PREVIEW_PRIOR_PALETTE='+json.dumps(colors,separators=(',',':'))+';\n'
text += 'export const PIECE_MATERIAL_PALETTES='+json.dumps(materials,separators=(',',':'))+';\n'
text += 'export const THROW_MATERIAL_PALETTES='+json.dumps(throw_materials,separators=(',',':'))+';\n'
text += 'export const PIECE_INITIAL_OBJ_PALETTE='+json.dumps(initial,separators=(',',':'))+';\n'
for path in [out/'preview-palettes.js',ROOT/'renderer/games/eggo-mania/assets/preview-palettes.js']:
    path.write_text(text,encoding='utf-8')
print(out)
